/**
 * Flow JSON → a Playwright spec.
 *
 * Selector strategies map onto Playwright's own semantic locators, which is why the schema
 * ordered them that way: getByTestId > getByRole > getByLabel > getByText > locator(css).
 */
import type { FlowDocument, FlowStep, Selector } from '../types/flow';

export function exportPlaywright(flow: FlowDocument): string {
  const lines: string[] = [];
  const secrets = flow.variables.filter((v) => v.kind === 'secret');
  const texts = flow.variables.filter((v) => v.kind === 'text');

  lines.push(`// Generated by eeveon-flow ${flow.provenance.recorder_version} from flow ${flow.flow_id}.`);
  lines.push('// Regenerate rather than editing: hand edits are lost on the next export.');
  lines.push("import { test, expect } from '@playwright/test';");
  lines.push('');

  if (texts.length > 0 || secrets.length > 0) {
    lines.push('const inputs = {');
    for (const variable of texts) {
      lines.push(`  ${variable.name}: process.env.${envName(variable.name)} ?? ${JSON.stringify(variable.default ?? '')},`);
    }
    for (const variable of secrets) {
      lines.push(`  ${variable.name}: requireEnv('${envName(variable.name)}'),`);
    }
    lines.push('};');
    lines.push('');
  }

  if (secrets.length > 0) {
    lines.push('function requireEnv(name: string): string {');
    lines.push('  const value = process.env[name];');
    lines.push('  if (!value) throw new Error(`missing required secret: ${name}`);');
    lines.push('  return value;');
    lines.push('}');
    lines.push('');
  }

  lines.push(`test(${JSON.stringify(flow.name)}, async ({ page }) => {`);

  for (const step of flow.steps) {
    lines.push(`  // ${step.index + 1}. ${step.intent}`);
    const checkpoint = flow.checkpoints.find((c) => c.before_step === step.step_id);
    if (checkpoint) {
      lines.push(`  // APPROVAL (${checkpoint.severity}): ${checkpoint.reason}`);
    }
    lines.push(...emitStep(step).map((line) => `  ${line}`));
    lines.push('');
  }

  lines.push('});');
  lines.push('');

  return lines.join('\n');
}

function emitStep(step: FlowStep): string[] {
  const locator = step.target ? locatorFor(step.target.selectors) : null;

  switch (step.verb) {
    case 'navigate':
      return [`await page.goto(${JSON.stringify(step.url ?? '')});`];

    case 'click':
      if (!locator) return ['// skipped: click with no resolvable target'];
      return [
        `await ${locator}.click();`,
        ...(step.url ? [`await expect(page).toHaveURL(${JSON.stringify(step.url)});`] : []),
      ];

    case 'type':
      if (!locator) return ['// skipped: type with no resolvable target'];
      return [`await ${locator}.fill(${valueExpr(step)});`];

    case 'select':
      if (!locator) return ['// skipped: select with no resolvable target'];
      if (step.target?.tag === 'select') return [`await ${locator}.selectOption(${valueExpr(step)});`];
      return [`await ${locator}.check();`];

    case 'submit':
      if (!locator) return ['await page.keyboard.press(\'Enter\');'];
      return [
        `await ${locator}.press('Enter');`,
        ...(step.url ? [`await expect(page).toHaveURL(${JSON.stringify(step.url)});`] : []),
      ];

    case 'key_press':
      return [`await page.keyboard.press(${JSON.stringify(playwrightKey(step))});`];

    case 'scroll':
      return ['await page.mouse.wheel(0, 600);'];

    case 'hover':
      if (!locator) return ['// skipped: hover with no resolvable target'];
      return [`await ${locator}.hover();`];

    case 'wait':
      return ["await page.waitForLoadState('networkidle');"];

    case 'assert':
      if (!locator) return ['// skipped: assert with no resolvable target'];
      return [`await expect(${locator}).toBeVisible();`];

    default:
      return [`// unsupported verb: ${step.verb}`];
  }
}

/** First selector that maps to a Playwright locator; falls back to the raw css path. */
function locatorFor(selectors: Selector[]): string {
  for (const selector of selectors) {
    switch (selector.strategy) {
      case 'testid':
        return `page.getByTestId(${JSON.stringify(selector.value)})`;
      case 'role': {
        const parsed = /^([a-z]+)\[name="(.*)"\]$/s.exec(selector.value);
        if (!parsed) break;
        return `page.getByRole(${JSON.stringify(parsed[1])}, { name: ${JSON.stringify(parsed[2])} })`;
      }
      case 'label':
        return `page.getByLabel(${JSON.stringify(selector.value)})`;
      case 'text':
        return `page.getByText(${JSON.stringify(selector.value)}, { exact: true })`;
      case 'name':
        return `page.locator(${JSON.stringify(`[name="${selector.value}"]`)})`;
      case 'id':
        return `page.locator(${JSON.stringify(`#${selector.value}`)})`;
      case 'css':
        return `page.locator(${JSON.stringify(selector.value)})`;
      default:
        break;
    }
  }
  const fallback = selectors[0];
  return fallback ? `page.locator(${JSON.stringify(fallback.value)})` : 'page.locator(\'body\')';
}

function valueExpr(step: FlowStep): string {
  const value = step.value;
  if (!value) return "''";
  if (value.kind === 'literal') return JSON.stringify(value.text);
  return `inputs.${value.variable}`;
}

function playwrightKey(step: FlowStep): string {
  const raw = step.value?.kind === 'literal' ? step.value.text : 'Enter';
  // "Ctrl+Meta+k" from the recorder is "Control+Meta+k" in Playwright.
  return raw.replace(/\bCtrl\b/g, 'Control');
}

function envName(variable: string): string {
  return variable.toUpperCase();
}
